describe('the hidden journey Mose (id mose)', () => {
  it('a normal build (without Mose) never adds it, even with the unlock link', async () => {
    vi.stubEnv('VITE_INCLUDE_MOSE', 'false')
    open('?mose=mose-vorschau-q4t8')
    const m = await load()
    await m.loadPreviewJourneys()
    expect(m.journeys.map((j) => j.id)).toEqual(['josef'])
    expect(m.journeyById('mose')).toBeUndefined()
  })

  it('the test build without the link does not show it; a wrong code does not unlock it', async () => {
    vi.stubEnv('VITE_INCLUDE_MOSE', 'true')
    const m = await load()
    await m.loadPreviewJourneys()
    expect(m.journeys.map((j) => j.id)).toEqual(['josef'])
    open('?mose=raten')
    const wrong = await load()
    await wrong.loadPreviewJourneys()
    expect(wrong.journeys.map((j) => j.id)).toEqual(['josef'])
    expect(localStorage.getItem(wrong.MOSE_PREVIEW_KEY)).toBeNull()
  })

  it('the unlock link shows it (the code leaves the address bar), the device remembers it, ?mose=off locks it again', async () => {
    vi.stubEnv('VITE_INCLUDE_MOSE', 'true')
    const first = await load()
    open(`?mose=${first.MOSE_UNLOCK_CODE}#/app/adventure`)
    await first.loadPreviewJourneys()
    expect(first.MOSE_UNLOCK_CODE).toBe('mose-vorschau-q4t8')
    expect(first.journeys.map((j) => j.id)).toEqual(['josef', 'mose'])
    expect(localStorage.getItem('lk-preview-mose')).toBe('1')
    expect(window.location.search).toBe('')
    const again = await load()
    await again.loadPreviewJourneys()
    expect(again.journeyById('mose')?.stages.length).toBe(15)
    open('?mose=off')
    const off = await load()
    await off.loadPreviewJourneys()
    expect(off.journeys.map((j) => j.id)).toEqual(['josef'])
    expect(localStorage.getItem('lk-preview-mose')).toBeNull()
  })

  it('the unlock is independent of the other hidden journeys', async () => {
    for (const k of ['MOSE', 'GIDEON']) vi.stubEnv(`VITE_INCLUDE_${k}`, 'true')
    localStorage.setItem('lk-preview-mose', '1')
    const only = await load()
    await only.loadPreviewJourneys()
    expect(only.journeys.map((j) => j.id)).toEqual(['josef', 'mose'])
    localStorage.setItem('lk-preview-gideon', '1')
    const both = await load()
    await both.loadPreviewJourneys()
    expect(both.journeys.map((j) => j.id).sort()).toEqual(['gideon', 'josef', 'mose'])
  })

  it('local mode (VITE_SHOW_MOSE) shows it on every device and loading twice adds it once', async () => {
    vi.stubEnv('VITE_SHOW_MOSE', 'true')
    const m = await load()
    await m.loadPreviewJourneys()
    await m.loadPreviewJourneys()
    expect(m.journeys.filter((j) => j.id === 'mose')).toHaveLength(1)
  })
})
